export function isValidIata(code: string): boolean {
  return /^[A-Z]{3}$/.test(code) && KNOWN_IATA_CODES.has(code);
}

export function validateIata(code: string, fieldName = "Airport code"): void {
  if (!isValidIata(code)) {
    throw new Error(`${fieldName} '${code}' is not a recognised IATA code`);
  }
}
